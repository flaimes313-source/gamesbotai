def random_joke(category: str | None = None) -> str:
    """
    Возвращает случайный прикол.
    Если category указан и есть в словаре — из этой категории,
    иначе — из всех приколов.
    """
    if category and category in _JOKES:
        return random.choice(_JOKES[category])

    all_jokes = [j for jokes in _JOKES.values() for j in jokes]
    return random.choice(all_jokes) if all_jokes else "😂"


def categories() -> list[str]:
    """Возвращает список категорий (без 'Случайный')."""
    return list(_JOKES.keys())